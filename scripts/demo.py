"""Run every assignment scenario end to end and write the evidence to ./examples.

    python scripts/demo.py

Produces annotated images, per-image metadata JSON, before/after of manual correction, composites and RESULTS.md.
Uses a throw-away catalog, so it never touches your real data.
"""
import json
import shutil
import sys
import tempfile
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app import compose                     # noqa: E402
from app.catalog import Catalog              # noqa: E402
from app.compose import CompositionError     # noqa: E402
from app.evaluate import run as run_eval     # noqa: E402

OUT = ROOT / "examples"
TEST = ROOT / "data" / "testset"
AUTO, USER = (92, 200, 255), (255, 180, 84)
log = []


def say(s=""):
    print(s); log.append(s)


def annotate(cat, image_id, path):
    """Draw boxes: blue = automatic, amber = added/edited by a person, dashed = needs review."""
    d = cat.get_image(image_id)
    im = Image.open(cat.image_path(image_id)).convert("RGB")
    dr = ImageDraw.Draw(im)
    try:
        f = ImageFont.truetype("DejaVuSans-Bold.ttf", max(12, im.width // 48))
    except Exception:
        f = ImageFont.load_default()
    for o in d["objects"]:
        if o["deleted"]:
            continue
        col = USER if (o["origin"] == "manual" or o["edited"] or o["reviewed"]) else AUTO
        x, y, w, h = o["bbox"]
        if o["needs_review"]:
            for t in range(0, w, 14):
                dr.line([(x + t, y), (x + min(t + 7, w), y)], fill=col, width=3); dr.line([(x + t, y + h), (x + min(t + 7, w), y + h)], fill=col, width=3)
            for t in range(0, h, 14):
                dr.line([(x, y + t), (x, y + min(t + 7, h))], fill=col, width=3); dr.line([(x + w, y + t), (x + w, y + min(t + 7, h))], fill=col, width=3)
        else:
            dr.rectangle([x, y, x + w, y + h], outline=col, width=3)
        txt = f"{o['label']} {o['confidence']:.2f}"
        tb = dr.textbbox((0, 0), txt, font=f)
        ty = max(0, y - (tb[3] + 6))
        dr.rectangle([x, ty, x + tb[2] + 8, ty + tb[3] + 6], fill=col)
        dr.text((x + 4, ty + 2), txt, fill=(5, 20, 30), font=f)
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path)


def table(img):
    rows = ["| object | colour | confidence | box (x, y, w, h) | origin | fields |", "|---|---|---|---|---|---|"]
    for o in img["objects"]:
        fs = ",".join(k for k, v in o["field_source"].items() if v == "user") or "all auto"
        rows.append(f"| {o['label']}{' (removed)' if o['deleted'] else ''} | {o['color']} | {o['confidence']:.2f} | {tuple(o['bbox'])} | {o['origin']} | {fs} |")
    return "\n".join(rows)


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    tmp = Path(tempfile.mkdtemp())
    cat = Catalog(tmp / "store")
    ids = {}

    say("# Results (generated by scripts/demo.py)\n")
    say("## 1. Successful detection\n")
    say("Blue box = detected automatically. Dashed = below the 0.60 confidence threshold, flagged for review.\n")
    for n in ["apple", "orange", "boy", "girl", "shapes", "colors", "apple_orange", "overlapping_shapes"]:
        img = cat.add_image((TEST / f"{n}.png").read_bytes(), n, f"{n}.png")
        ids[n] = img["id"]
        annotate(cat, img["id"], OUT / "detection" / f"{n}.png")
        (OUT / "metadata").mkdir(exist_ok=True)
        (OUT / "metadata" / f"{n}.json").write_text(json.dumps(img, indent=2))
        say(f"### {n}  \nstatus **{img['auto']['detection_status']}**, route `{img['auto']['route']}`, {img['auto']['detection_ms']:.0f} ms, "
            f"dominant colours {img['auto']['dominant_colors']}\n\n![{n}](detection/{n}.png)\n\n{table(img)}\n")

    say("## 2. Failed detection\n")
    for n, why in (("blank", "nothing to find"), ("low_contrast", "a light-grey disc on white, below the contrast threshold")):
        img = cat.add_image((TEST / f"{n}.png").read_bytes(), n, f"{n}.png"); ids[n] = img["id"]
        annotate(cat, img["id"], OUT / "failed" / f"{n}.png")
        (OUT / "metadata" / f"{n}.json").write_text(json.dumps(img, indent=2))
        say(f"### {n} ({why})\nstatus **{img['auto']['detection_status']}** - {img['auto']['detection_message']}  \nobjects: {len(img['objects'])}\n")

    say("## 3. Manual correction (source of truth)\n")
    lc = ids["low_contrast"]
    o = cat.add_object(lc, "circle", [100, 100, 200, 200], color="light gray", confidence=0.9)
    say("**Add** the missed object by hand:\n\n" + table(cat.get_image(lc)) + "\n")
    annotate(cat, lc, OUT / "manual" / "1_added.png")
    cat.update_object(o["id"], {"label": "light gray disc", "confidence": 0.95, "bbox": [96, 96, 208, 208]})
    say("**Edit** name, confidence and box (fields now marked `user`):\n\n" + table(cat.get_image(lc)) + "\n")
    annotate(cat, lc, OUT / "manual" / "2_edited.png")

    sh = ids["shapes"]; objs = {x["label"]: x for x in cat.get_image(sh)["objects"]}
    cat.update_object(objs["triangle"]["id"], {"label": "green triangle", "confidence": 0.7})
    cat.delete_object(objs["circle"]["id"])
    cat.add_object(sh, "logo", [20, 20, 40, 40], color="black")
    before = cat.get_image(sh)
    say("**Persistence**: on `shapes` the triangle was renamed, the circle removed and a logo added. Re-running detection in *keep my corrections* mode:\n")
    after = cat.detect(sh, "preserve_manual")
    say(table(after) + "\n")
    kept = {x["label"] for x in after["objects"] if not x["deleted"]}
    assert {"green triangle", "logo"} <= kept and "circle" not in kept
    say(f"Corrections survived: {sorted(kept)}; the removed circle did not come back.\n")
    after = cat.detect(sh, "replace_all")
    say("Only an explicit *replace everything* request discards them:\n\n" + table(after) + "\n")
    annotate(cat, sh, OUT / "manual" / "3_shapes_replaced.png")

    say("## 4. Composite generation\n")
    runs = [("Create an image containing one red apple and one orange", {}),
            ("Generate a composite containing a boy, a girl, and colored shapes", {}),
            ("a small apple to the left of a large orange on a blue background", {}),
            ("a boy on the left, a girl on the right and shapes in the middle", {}),
            ("a red circle in front of a blue square", {}),
            ("an orange above a red apple on a transparent background", {})]
    for i, (txt, kw) in enumerate(runs, 1):
        r = compose.compose(cat, txt, **kw)
        p = OUT / "composites" / f"{i}.png"; p.parent.mkdir(exist_ok=True)
        shutil.copyfile(cat.image_path(r["image"]["id"]), p)
        annotate(cat, r["image"]["id"], OUT / "composites" / f"{i}_annotated.png")
        (OUT / "composites" / f"{i}.json").write_text(json.dumps(r["image"], indent=2))
        say(f"### {txt}\n![composite {i}](composites/{i}.png)\n\nSaved as catalog entry `{r['image']['id']}`; every object was pasted from an existing asset:\n\n"
            + "\n".join(f"- {pl['label']} ({pl['color']}) from **{pl['asset_image_name']}**, scale {pl['scale']}, box {pl['bbox']}" for pl in r["placements"]) + "\n")

    say("### Missing asset: refuses instead of approximating\n")
    n_before = len(cat.list_images())
    try:
        compose.compose(cat, "an apple, an orange and a banana")
    except CompositionError as e:
        say(f"`an apple, an orange and a banana` -> **refused**: {e.missing}. Catalog entries before/after: {n_before}/{len(cat.list_images())}\n")
    try:
        compose.compose(cat, "a blue apple")
    except CompositionError as e:
        say(f"`a blue apple` -> **refused**: {e.missing}\n")

    say("## 5. Overlap and no-object cases\n")
    ov = cat.get_image(ids["overlapping_shapes"])
    say("`overlapping_shapes`: the circle is half hidden behind the square and the triangle's apex is hidden, yet each box covers the whole shape.\n\n"
        f"![overlap](detection/overlapping_shapes.png)\n\n{table(ov)}\n")
    say("`blank` and `low_contrast` return zero objects with an explicit status (section 2).\n")

    say("## Benchmark\n")
    ev = run_eval()
    s = ev["summary"]
    say("```json\n" + json.dumps(s, indent=2) + "\n```\n")
    say("| image | status | ground truth | detected | label/colour correct | mean IoU |\n|---|---|---|---|---|---|")
    for n, v in ev["images"].items():
        m = v["matched"]
        ok = sum(x["label_ok"] and x["color_ok"] for x in m)
        mi = f"{np.mean([x['iou'] for x in m]):.3f}" if m else "-"
        say(f"| {n} | {v['status']} | {v['n_gt']} | {v['n_det']} | {ok}/{len(m)} | {mi} |")
    say("\nReal photographs (OpenCV sample images, YOLOX-nano route):\n")
    say("| file | expected | detected | confidence | status |\n|---|---|---|---|---|")
    for f, v in ev["real_photos"].items():
        say(f"| {f} | {v['expected'][0]}/{v['expected'][1]} | {v['label']}/{v['color']} | {v['conf']} | {v['status']} |")
    (OUT / "RESULTS.md").write_text("\n".join(log))
    shutil.rmtree(tmp, ignore_errors=True)
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
